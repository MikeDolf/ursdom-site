def rule(alt):
    return re.compile(''.join('(?=.*' + re.escape(p).replace(r'\ ', ' ') + ')' for p in alt.split('+')))

RX = [(sec, name, have, [rule(a) for a in alts]) for sec, name, have, alts in PLAN]

taken = set()
res = []
for sec, name, have, rules in RX:
    tot, n = 0, 0
    for cl, ints, ph, fr, var in ROWS:
        if ph in taken:
            continue
        hay = ph + ' | ' + var
        if any(r.search(hay) for r in rules):
            taken.add(ph); tot += int(fr); n += 1
    res.append((sec, name, have, n, tot))

secs = collections.OrderedDict()
for sec, name, have, n, tot in res:
    secs.setdefault(sec, []).append((name, have, n, tot))

grand = sum(int(r[3]) for r in ROWS)
covered = sum(t for *_, t in res)
print(f'вся выгрузка после чистки: {grand} частотности, {len(ROWS)} схлопнутых групп')
print(f'план забирает: {covered} ({covered*100//grand}%), {len(taken)} групп, {len(res)} страниц\n')
for sec, items in secs.items():
    items.sort(key=lambda x: -x[3])
    ssum = sum(i[3] for i in items)
    print(f'--- {sec.upper()} : {len(items)} страниц, {ssum} частотности')
    for name, have, n, tot in items:
        mark = {'да': 'есть  ', 'частично': 'частич', 'нет': 'НОВАЯ '}[have]
        print(f'  {mark} {tot:7}  ({n:4} фраз)  {name}')
    print()

# что осталось за планом
rest = [(int(fr), ph, cl) for cl, ints, ph, fr, var in ROWS if ph not in taken]
rest.sort(reverse=True)
print(f'вне плана осталось {sum(f for f,_,_ in rest)} частотности. Топ-20:')
for f, ph, cl in rest[:20]:
    print(f'  {f:6}  [{cl}]  {ph}')
