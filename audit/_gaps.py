 ('Бетонный кирпич',                    'комм', ['кирпич+бетонн', 'бетонн+кирпич']),
 ('Строительная химия для бетона',      'комм', ['пропитк+бетон', 'топпинг', 'наливн+пол', 'эпоксидн+пол', 'упрочнител']),
