def bucket(store, inc, exc, minfreq):
    hits = []
    for p, ex in store.items():
        if ex < minfreq:
            continue
        if not any(i in p for i in inc):
            continue
        if exc and any(e in p for e in exc):
            continue
        hits.append((ex, p))
    hits.sort(reverse=True)
    return hits


