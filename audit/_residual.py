covered = 0
for cl, ints, ph, fr, var in ROWS:
    i = set(ints.split('|')) if ints else set()
    f = int(fr)
    hay = ph + ' | ' + var
    if any(r.search(hay) for r in RX):
        covered += f
        continue
    left.append((f, cl, ph, 'инфо' if (i & INFO) and 'коммерческий' not in i else 'комм'))

