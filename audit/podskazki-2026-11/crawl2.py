SKIP = re.compile(r"торф|чернозем|перегно|навоз|плодородн")


def main():
    done = set(open(DONE).read().split("\n")) if os.path.exists(DONE) else set()
    jobs = []
    for s in NEW_SEEDS:
        jobs.append((s, s))
        jobs += [(s, s + " " + c) for c in crawl.ALPHA]
        jobs += [(s, s + " " + m) for m in crawl.MODS]
    # второй уровень: лучшие справочные фразы первого сбора
    R = json.load(open(os.path.join(HERE, "sug.json")))
    info = [r for r in R if r["cls"] == "инфо" and not SKIP.search(r["q"])]
    info.sort(key=lambda r: -r["score"])
    seen_core, lvl2, alpha2 = set(), [], []
    for r in info:
        core = tuple(sorted(set(re.findall(r"[а-яa-z0-9]+", r["q"]))))
        if core in seen_core:
            continue
        seen_core.add(core)
        lvl2.append(r["q"])
        if len(lvl2) >= 700:
            break
    for q in lvl2:
        jobs.append(("L2:" + q, q))
    for q in [q for q in lvl2 if 2 <= len(q.split()) <= 3][:160]:
        jobs += [("L2:" + q, q + " " + c) for c in crawl.ALPHA]
    tasks = [(seed, q, eng) for seed, q in jobs for eng in ("ya", "gg") if eng + "|" + q not in done]
    print("новых заданий", len(tasks), flush=True)
    out, dn, lock, cnt = open(OUT, "a"), open(DONE, "a"), threading.Lock(), [0]
    FN = {"ya": crawl.ya, "gg": crawl.gg}

    def work(t):
        seed, q, eng = t
        res = None
        for attempt in range(3):
            try:
                res = FN[eng](q)
                break
            except Exception:
                time.sleep(3 * (attempt + 1))
        with lock:
            if res is None:
                print("ошибка", eng, q, flush=True)
                return
            out.write(json.dumps({"e": eng, "seed": seed, "q": q, "s": res}, ensure_ascii=False) + "\n")
            dn.write(eng + "|" + q + "\n")
            cnt[0] += 1
            if cnt[0] % 1000 == 0:
                out.flush(); dn.flush()
                print(cnt[0], "из", len(tasks), flush=True)
        time.sleep(0.2 + random.random() * 0.3)

    with ThreadPoolExecutor(8) as ex:
        list(ex.map(work, tasks))
    out.close(); dn.close()
    print("готово", cnt[0], flush=True)


if __name__ == "__main__":
    main()
