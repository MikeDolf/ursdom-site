OPERATOR = {
    "name": None,      # например: ИП Иванов Иван Иванович
    "inn": None,
    "ogrn": None,
    "address": None,
}

def operator_block(cfg):
    """Текст про оператора: с реквизитами, если они есть, иначе честно без них."""
    if OPERATOR["name"]:
        parts = [OPERATOR["name"]]
        if OPERATOR["inn"]:
            parts.append("ИНН " + OPERATOR["inn"])
        if OPERATOR["ogrn"]:
            parts.append("ОГРН " + OPERATOR["ogrn"])
        if OPERATOR["address"]:
            parts.append("адрес: " + OPERATOR["address"])
        return ", ".join(parts) + f". Связь по вопросам обработки данных: {cfg['email']}."
    return (
        "Оператором обработки является владелец сайта, ведущий деятельность по доставке "
        f"нерудных материалов по {cfg['region_dat']}. Связь по любым вопросам обработки "
        f"данных, включая отзыв согласия: {cfg['email']}, а также через мессенджер MAX "
        "по ссылке в шапке раздела."
    )


