import re

# Порядок важен: признаки проверяются сверху вниз, на страницу идут
# первые два найденных. Сырость и выработки стоят первыми, потому что
# именно они чаще всего ломают основание, и совет по ним нужнее.
GROUND_FLAGS = [
    ("wet", r"пойм|заболоч|низин|подтап|сыр|стоит вода|раскиса"),
    ("mine", r"выработ|отвал|техноген|просадоч|разработ"),
    ("karst", r"карст|известняк"),
    ("clay", r"суглин|глин"),
    ("rock", r"скаль|каменист|щебенист|горная|предгор"),
    ("sand", r"супес|песчан"),
]


def ground_flags(ground, limit=2):
    """Признаки грунта из описания города, не больше limit штук."""
    out = [k for k, pat in GROUND_FLAGS if re.search(pat, ground)]
    return out[:limit]


