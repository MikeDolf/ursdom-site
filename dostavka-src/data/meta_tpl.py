# -*- coding: utf-8 -*-
"""Генератор Title и Description для каталожных страниц.

ЗАЧЕМ ШАБЛОН, А НЕ РУЧНОЙ ТЕКСТ. Теговых страниц по параметрам будет
много: фракции, виды песка, типы бордюра, размеры колец. Писать каждый
заголовок руками означает получить разнобой в длине и в порядке слов,
а потом не суметь массово поправить формулу.

ЧЕГО ШАБЛОН НЕ ДЕЛАЕТ. Он не заменяет уникальность: два разных товара
с одинаковым набором переменных дадут одинаковый Title, и это поймает
группа 14 в audit/_verify.py, которая уже проверяет дубли мета по всему
сайту. Шаблон задаёт форму, различие обеспечивают данные.

ПОРЯДОК СЛОВ выбран по тому, как люди читают выдачу: сначала предмет
запроса, потом уточняющий параметр, потом гео, в конце коммерческий
хвост. «Щебень 20-40 с доставкой в Екатеринбурге: цена за куб» читается
слева направо ровно так, как формулируется запрос.

ЛИМИТЫ. Title до 70 символов, дальше Яндекс и Гугл режут. Description
до 200: группа «мета» в _verify.py падает на 201 и выше, это уже
случалось и стоило одной пересборки.
"""

TITLE_LIMIT = 70
DESC_LIMIT = 200

# Гео-варианты. Первый идёт в Title, второй в Description: повтор
# одного и того же города дважды подряд выглядит как переспам.
GEO_SHORT = "в Екатеринбурге"
GEO_FULL = "по Екатеринбургу и Свердловской области"


def title(subject, param=None, tail="цена за куб", geo=GEO_SHORT):
    """'Щебень' + '20-40' -> 'Щебень 20-40 с доставкой в Екатеринбурге: цена за куб'."""
    head = subject if not param else f"{subject} {param}"
    out = f"{head} с доставкой {geo}: {tail}"
    if len(out) > TITLE_LIMIT:                 # хвост режется первым
        out = f"{head} с доставкой {geo}"
    if len(out) > TITLE_LIMIT:                 # потом гео
        out = f"{head} с доставкой"
    return out


def description(subject, param=None, what="", low=None, unit="за куб",
                geo=GEO_FULL, extra=""):
    """Description с ценой: цифра в сниппете поднимает кликабельность.

    Цена ставится в формулировке «от», как и везде на сайте: точной
    прайс-листовой цены у нас нет, и обещать её в сниппете нельзя.
    """
    head = subject if not param else f"{subject} {param}"
    bits = [f"{head} с доставкой {geo}."]
    if what:
        bits.append(what.rstrip(".") + ".")
    if low:
        bits.append(f"Цена от {low} рублей {unit}.")
    if extra:
        bits.append(extra.rstrip(".") + ".")
    out = " ".join(bits)
    while len(out) > DESC_LIMIT and len(bits) > 1:
        bits.pop()                             # отрезаем с хвоста
        out = " ".join(bits)
    return out[:DESC_LIMIT].rstrip()


def h1(subject, param=None, geo="по Екатеринбургу и области"):
    """H1 не повторяет Title дословно: у них разная работа.

    Title продаёт клик в выдаче и несёт коммерческий хвост. H1 называет
    страницу человеку, который уже пришёл, и хвост ему не нужен.
    """
    head = subject if not param else f"{subject} {param}"
    return f"{head} с доставкой {geo}"
