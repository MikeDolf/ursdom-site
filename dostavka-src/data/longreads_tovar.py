_MYT_ROWS = [[q[0], q[2] + " " + q[3], q[4]] for q in _MYT]
_MYT_MIN = min(int(q[2].replace(" ", "")) for q in _MYT)
_MYT_MAX = max(int(q[2].replace(" ", "")) for q in _MYT)

