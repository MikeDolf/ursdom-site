from prices import PESOK_QUARRIES, PER_CUBE

# Насыпная плотность отсева 0-5 из блока характеристик товарной страницы
# (products.MATERIALS["otsev"]). Всё, что ниже про мешки, считается от неё,
# а не набирается руками: ошибка в одном умножении на такой странице
# вскрывается уже на объекте, когда мешков не хватило.
OTSEV_D = (1.40, 1.50)

# Цена навала берётся из прайса, а не дублируется строкой.
_rub_otsev = "".join(c for c in PER_CUBE["Отсев 0-5"] if c.isdigit())


def _bags(kg):
    """Сколько мешков по kg килограммов уходит на кубометр."""
    lo = int(OTSEV_D[0] * 1000 // kg)
    hi = int(OTSEV_D[1] * 1000 // kg)
    return "%d" % lo if lo == hi else "%d-%d" % (lo, hi)


def _vol(kg):
    """Объём одного мешка в кубометрах, округлённый до сотых или тысячных."""
    v = kg / ((OTSEV_D[0] + OTSEV_D[1]) / 2 * 1000.0)
    return ("около %.3f м³" % v).replace(".", ",") if v < 0.1 else \
           ("около %.2f м³" % v).replace(".", ",")


def _need(m2, sm):
    """Объём и число мешков по 25 кг на площадь m2 при слое sm сантиметров."""
    v = m2 * sm / 100.0
    n = int(round(v * (OTSEV_D[0] + OTSEV_D[1]) / 2 * 1000 / 25))
    return ("%.2f" % v).rstrip("0").rstrip(".").replace(".", ","), n

# Строки прайса, где единица - тонна: это и есть мытый песок. Строительный
# идёт кубами и на эту страницу не попадает. Фильтр по единице, а не по
# названию карьера: добавится карьер - строка появится сама.
