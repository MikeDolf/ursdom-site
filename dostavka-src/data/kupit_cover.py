def load():
    """[(материал, запрос, частота, причина_отказа_или_None)]."""
    out = []
    files = [(f, os.path.basename(f).replace("_купить.csv", "").replace("_", " "))
             for f in sorted(glob.glob(os.path.join(KUPIT_DIR, "*.csv")))]
    for d in sorted(glob.glob(SYN_DIR + "*")):
        files += [(f, SYN.get(os.path.basename(f).replace("_купить.csv", "").replace("_", " "), None))
                  for f in sorted(glob.glob(os.path.join(d, "*.csv")))]
    for f, mat in files:
        with open(f, encoding="utf-8-sig") as fh:
            rows = list(csv.reader(fh))[1:]
        for q, n in rows:
            q = " ".join(q.lower().replace("ё", "е").split())
            why = None
            if mat is None:
                why = "другое значение слова"
            elif mat == "-":
                why = NOT_OURS
            elif OTHER_REGION.search(q):
                why = "чужой регион"
            elif OFF_TOPIC.search(q):
                why = "не наш товар или магазин"
            elif JUNK.search(q):
                why = "обрывок запроса"
            out.append((mat, q, int(n), why))
    return out


