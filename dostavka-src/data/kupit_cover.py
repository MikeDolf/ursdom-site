    s = re.sub(r"(?<!\d)31 5 63(?!\d)", "31,5-63", s)
    words = []
    for w in s.split():
        if w in _UPPER:
            words.append(_UPPER[w])
        elif w in _PROPER:
            words.append(w[0].upper() + w[1:])
        else:
            words.append(w)
    s = " ".join(words)
    s = s.replace("Н. Тагил", "Н. Тагил")
    return s[0].upper() + s[1:]


