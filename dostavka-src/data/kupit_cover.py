def type_note(mat, q, page):
    key = "мрамор" if page == "shcheben/mramornyy" else mat
    for rx, txt in TYPE.get(key, []):
        if re.search(rx, q):
            return txt
    if key == "мрамор":
        return "Декоративный и мраморный щебень подтверждаем по заявке."
    return None


def answer(mat, q, page):
    m = MAT[mat]
    parts = []
    here_city = page.split("/")[-1] if "/" in page else None
    # фракция
    frac = None
    for pr in FRAC_PAIRS:
        a, b = pr.split()
        if re.search(r"(?<!\d)%s\s*[ х]\s*%s(?!\d)" % (a, b), q):
            frac = "%s-%s" % (a, b)
            break
    if mat == "щебень" and frac in SH_FRAC and page != "shcheben/mramornyy":
        parts.append("Щебень %s от %d руб/м³ на площадке." % (frac, SH_FRAC[frac]))
    elif mat == "щебень" and frac:
        parts.append("Фракцию %s подтверждаем по заявке, ходовые 5-20, 20-40 и 40-70 всегда "
                     "в наличии." % frac)
    elif mat == "керамзит" and frac:
        parts.append("Керамзит %s от 1500 руб/м³ навалом, фракцию подтверждаем по заявке." % frac)
    else:
        tn_ = type_note(mat, q, page)
        if tn_:
            parts.append(tn_)
        elif frac and m["price"]:
            parts.append("%s от %d руб/м³, фракцию подтверждаем по заявке." % (m["name"], m["price"]))
    # тонны и кубы: фракцию вырезаем, иначе «5 20 куб» читается как 20 кубов
    qv = q
    if frac:
        a, b = frac.split("-")
        qv = re.sub(r"(?<!\d)%s\s*[ х]\s*%s(?!\d)" % (a, b), " ", q)
    t = re.search(r"(\d+)\s*(?:тонн|тонны|тонну|тонна|тона|тон\b|т\b|1000кг)", qv)
    c = re.search(r"(\d+)\s*(?:куб|м3|кубов|куба|кубометр)", qv) or \
        re.search(r"(шесть) кубов", qv)
    tn = 1.0 if "1000кг" in q else (float(t.group(1)) if t else None)
    if re.search(r"\bтонн[уа]\b|\bтона\b", qv) and not t:
        tn = 1.0
    if tn and m.get("dens"):
        parts.append("%s т %s это около %s м³, считаем и возим в кубах."
                     % (_num(tn), m["rod"], _num(tn / m["dens"])))
    elif c:
        v = 6.0 if c.group(1) == "шесть" else float(c.group(1))
        s_ = "%s м³ %s" % (_num(v), m["rod"])
        if m.get("dens"):
            s_ += " это около %s т" % _num(v * m["dens"])
