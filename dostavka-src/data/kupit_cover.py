def build_rows():
    """{ключ страницы: [(подпись запроса, ответ, частота), ...]} и отчёт."""
    rows, skipped = {}, []
    seen = set()
    for mat, q, n, why in load():
        if why:
            skipped.append((mat, q, n, why))
            continue
        if q in seen:
            continue
        seen.add(q)
        page = route(mat, q)
        rows.setdefault(page, []).append((disp(q), answer(mat, q, page), n, mat))
    for k in rows:
        rows[k].sort(key=lambda r: -r[2])
    return rows, skipped


KUPIT_ROWS, KUPIT_SKIPPED = build_rows()


