# Мелкий объём: сколько мешков. Только у материалов, у которых мешок
# описан на наших же страницах (керамзит: 0,05 м³, 20 мешков на куб).
BAG_M3 = {"keramzit": 0.05}


def _num(x):
    r = "%.1f" % x
    return (r[:-2] if r.endswith(".0") else r).replace(".", ",")


def _vol(x):
    """Округление вверх до половины куба, для малых объёмов до десятой."""
    if x < 2:
        return math.ceil(x * 10) / 10
    return math.ceil(x * 2) / 2


def _truck(slug, v):
    if slug in BAG_M3 and v <= 1:
        return "%d мешков по %s м³ или самосвал 5 м³" % (
            math.ceil(v / BAG_M3[slug]), ("%g" % BAG_M3[slug]).replace(".", ","))
    n, cap = trips(v)
    if n == 1:
        tail = ", рейс оплачивается целиком" if v < 5 else ""
        return "самосвал %d м³%s" % (cap, tail)
    return "%d рейса по %d м³" % (n, cap) if n < 5 else "%d рейсов по %d м³" % (n, cap)


def task_rows(slug):
    """[(задача, объём, машина)] или None, если своей таблицы нет."""
    if slug not in TASKS:
        return None
    k, _, rows = TASKS[slug]
    out = []
    for label, area, layer in rows:
        v = _vol(area * layer * k)
        out.append((label, "около %s м³" % _num(v), _truck(slug, v)))
    return out


def task_caption(slug):
    if slug not in TASKS:
        return None
    return ("%s Машина по нашему парку: самосвалы на 5, 10 и 20 м³."
            % TASKS[slug][1])
