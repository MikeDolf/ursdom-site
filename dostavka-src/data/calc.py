"""Калькулятор доставки: данные и предрасчёт статичных примеров.

ГЛАВНОЕ ПРО ЧЕСТНОСТЬ. Тариф назван владельцем как «очень примерно»,
и калькулятор обязан говорить это вслух, а не выдавать цифру за счёт.
Поэтому результат везде подписан как предварительный, а кнопка ведёт
на заявку: точную сумму называет человек, а не скрипт.

АРХИТЕКТУРА. Блок работает БЕЗ JavaScript. На сервере, то есть на сборке,
рендерится настоящая таблица примеров расчёта: она видна поисковику,
читается со скринридера и работает при отключённом скрипте. JavaScript
только надстраивает над ней интерактив с ползунком. Обратный порядок,
когда виджет существует только в скрипте, дал бы пустой блок в индексе
и пустой блок у части посетителей.

ЧТО ЗДЕСЬ МОЖНО ПРАВИТЬ ОДНИМ ЧИСЛОМ:
- RATE_PER_KM: тариф за километр;
- EKB_KM: плечо «по городу» от склада под Екатеринбургом. Значение
  поставлено как ориентир и подлежит замене на фактическое, когда
  владелец его назовёт;
- TRUCKS: парк по вместимости кузова.
"""
