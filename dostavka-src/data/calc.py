MATERIALS = [(label, FLOOR[key]) for label, key in _PICK]


def _km(slug):
    f = CITY_FACTS.get(slug) or {}
    return f.get("km")


# Направления: Екатеринбург плюс города, у которых плечо известно
# фактически. Города без километража в калькулятор не попадают:
# придумывать им расстояние нельзя, а показывать ноль нечестно.
DESTINATIONS = [("Екатеринбург и ближний пояс", EKB_KM)]
for _c in CITIES:
    _d = _km(_c["slug"])
    if _d:
        DESTINATIONS.append((_c["name"], _d))
DESTINATIONS.sort(key=lambda x: x[1])


def trips(volume):
    """Сколько рейсов и каким кузовом.

    Возвращает (число рейсов, вместимость кузова). Объём сверх самого
    большого кузова везётся несколькими рейсами: это и есть та часть
    расчёта, которую обычные калькуляторы не показывают, а она меняет
    итог сильнее, чем цена за куб.
    """
    for cap, _ in TRUCKS:
        if volume <= cap:
            return 1, cap
    big = TRUCKS[-1][0]
    return -(-volume // big), big          # деление вверх без math.ceil


def estimate(volume, price_per_cube, km):
    """Предварительный расчёт. Возвращает словарь со всеми слагаемыми."""
    n, cap = trips(volume)
    material = volume * price_per_cube
    delivery = n * km * ROUND_TRIP * RATE_PER_KM
    return {
        "volume": volume, "trips": n, "capacity": cap,
        "material": material, "delivery": delivery,
        "total": material + delivery,
        "below_min": volume < MIN_VOLUME,
    }


