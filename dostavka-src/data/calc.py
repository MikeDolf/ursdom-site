# Плечи для примеров. Три точки: город, ближний пояс, дальний север.
EXAMPLE_ROUTES = (("Екатеринбург", EKB_KM), ("Первоуральск", ship_km("pervouralsk")),
                  ("Нижний Тагил", ship_km("nizhniy-tagil")))


def examples(material, price, volumes):
    """Статические строки таблицы, которые видны без JavaScript.

    Это же наполнение служит проверкой скрипта: цифры в таблице и
    в интерактиве обязаны совпадать при одних входных данных.
    """
    rows = []
    for vol in volumes:
        for city, km in EXAMPLE_ROUTES:
            e = estimate(vol, price, km)
            rows.append([
                f"{vol} м³", city, f"{km} км",
                f"{e['trips']} × {e['capacity']} м³",
                f"{e['material']:,}".replace(",", " "),
                f"{e['delivery']:,}".replace(",", " "),
                f"{e['total']:,}".replace(",", " "),
            ])
    return {"material": material, "price": price, "rows": rows}


def calc_for(slug):
    """Конфиг калькулятора для конкретной страницы или None."""
    got = PER_PAGE.get(slug)
    if not got:
        return None
    material, key, volumes = got
    price = FLOOR[key]
    return {
        "rate": RATE_PER_KM,
        "round_trip": ROUND_TRIP,
        "min_volume": MIN_VOLUME,
        "trucks": TRUCKS,
        "materials": MATERIALS,
        "destinations": DESTINATIONS,
        "default_price": price,
        "examples": examples(material, price, volumes),
        # Стартовое состояние рендерится на сборке. Без него блок
        # результата пуст до загрузки скрипта, а проверка соответствия
        # классов и стилей не видит разметку, которую рисует только JS.
        "start": _start(MATERIALS[0][1], 10, EKB_KM),
    }


def calc_geo(price_key, slug, vol, head=None):
    """Калькулятор городской страницы: сразу выбраны город и материал.

    Человек пришёл по запросу «отсев с доставкой в Ревду», и калькулятор,
    открывшийся на Екатеринбурге и щебне, заставлял его первым делом
    перещёлкивать оба списка. Здесь стартовое состояние - его город,
    материал страницы и объём, ходовой для этого плеча.

    Таблица примеров (запасной вид без JavaScript) не выводится: на той
    же странице выше стоит таблица «Сколько стоит машина» с теми же
    числами для этого города.
    """
    label = next(l for l, k in _PICK if k == price_key)
    price = FLOOR[price_key]
    km = ship_km(slug)
    return {
        "rate": RATE_PER_KM,
        "round_trip": ROUND_TRIP,
        "min_volume": MIN_VOLUME,
        "trucks": TRUCKS,
        "materials": MATERIALS,
        "destinations": DESTINATIONS,
        "default_price": price,
        "examples": examples(label, price, (vol,)),
        "start": _start(price, vol, km),
        "sel_mat": label,
        "sel_dest": CITY_FACTS[slug]["name"],
        "static": False,
        "head": head,
    }


def _fmt(n):
    return f"{n:,}".replace(",", " ")


def _start(price, vol, km):
    e = estimate(vol, price, km)
    return {"vol": vol, "km": km, "trips": e["trips"], "capacity": e["capacity"],
            "price_s": _fmt(price), "material_s": _fmt(e["material"]),
            "delivery_s": _fmt(e["delivery"]), "total_s": _fmt(e["total"])}
